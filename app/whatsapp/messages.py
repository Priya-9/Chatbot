"""Channel-agnostic message types. The journey engine produces these; senders turn them into API payloads."""

from dataclasses import dataclass, field


@dataclass
class Incoming:
    wa_id: str
    message_id: str
    type: str  # text | interactive | button | image | audio | ...
    text: str = ""  # typed text, or the title of the tapped button/row
    reply_id: str | None = None  # id of the tapped button/list row
    name: str | None = None  # WhatsApp profile name


@dataclass
class TextOut:
    body: str
    ai: bool = False  # True when generated by the LLM (kept as conversation memory)


@dataclass
class ButtonsOut:
    """Up to 3 reply buttons (WhatsApp limit)."""

    body: str
    buttons: list[tuple[str, str]]  # (id, title)


@dataclass
class ListOut:
    """Interactive list: up to 10 rows (WhatsApp limit)."""

    body: str
    button: str
    rows: list[tuple[str, str, str]] = field(default_factory=list)  # (id, title, description)
    section_title: str = ""


Outgoing = TextOut | ButtonsOut | ListOut


def outgoing_as_text(out: Outgoing) -> str:
    """Plain-text rendering, used for logging and the console simulator."""
    if isinstance(out, TextOut):
        return out.body
    if isinstance(out, ButtonsOut):
        return out.body + "\n" + "  ".join(f"[{title}]" for _, title in out.buttons)
    lines = [out.body, f"<{out.button}>"]
    lines += [f"  • {title}" + (f" — {desc}" if desc else "") for _, title, desc in out.rows]
    return "\n".join(lines)
